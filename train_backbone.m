function [net, info] = train_backbone(cfg)
%TRAIN_BACKBONE Train InceptionTurkerNeXt on the multi-cancer dataset.
%   Uses the hyperparameters of Section 3.2. Folder names of cfg.mcTrainDir
%   are the class labels (alphabetical order = class indices 1-26).
imdsTrain = imageDatastore(cfg.mcTrainDir, 'IncludeSubfolders', true, 'LabelSource', 'foldernames');
[imdsTr, imdsVal] = splitEachLabel(imdsTrain, 1 - cfg.train.valFraction, 'randomized');
aug = @(ds) augmentedImageDatastore([cfg.inputSize 3], ds, 'ColorPreprocessing', 'gray2rgb');
numClasses = numel(categories(imdsTrain.Labels));
lgraph = itn_architecture(numClasses);
opts = trainingOptions(cfg.train.solver, ...
    'MiniBatchSize', cfg.train.miniBatch, ...
    'InitialLearnRate', cfg.train.initLearnRate, ...
    'LearnRateSchedule', 'piecewise', ...
    'LearnRateDropFactor', cfg.train.dropFactor, ...
    'LearnRateDropPeriod', cfg.train.dropPeriod, ...
    'L2Regularization', cfg.train.l2, ...
    'Momentum', cfg.train.momentum, ...
    'MaxEpochs', cfg.train.maxEpochs, ...
    'Shuffle', 'every-epoch', ...
    'ValidationData', aug(imdsVal), ...
    'ValidationFrequency', floor(numel(imdsTr.Files) / cfg.train.miniBatch), ...
    'Verbose', true, 'Plots', 'none');
[net, info] = trainNetwork(aug(imdsTr), lgraph, opts);
end
